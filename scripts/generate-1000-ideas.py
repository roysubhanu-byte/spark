def to_typescript(ideas, var_name):
    """Convert ideas list to TypeScript source."""
    lines = [f"// Auto-generated by generate-1000-ideas.py"]
    lines.append(f"// {len(ideas)} ideas")
    lines.append(f"import type {{ Idea }} from '../types'")
    lines.append(f"")
    lines.append(f"export const {var_name}: Idea[] = ")

    # Use JSON and fix the typing
    json_str = json.dumps(ideas, indent=2, ensure_ascii=False)
    lines.append(json_str)

    return "\n".join(lines)



def make_id(name):
    return name.lower().replace("&", "and").replace("(", "").replace(")", "").replace("/", "-").replace(" ", "-").replace("--", "-").strip("-")


def make_badges(pool):
    count = random.randint(1, 3)
    return random.sample(pool, min(count, len(pool)))


